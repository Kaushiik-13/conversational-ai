CREATE TABLE catalog.categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES catalog.categories (id),
    slug text NOT NULL,
    name text NOT NULL,
    path ltree NOT NULL,
    depth smallint NOT NULL,
    is_security_domain boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT categories_sibling_slug_unique UNIQUE NULLS NOT DISTINCT (parent_id, slug),
    CONSTRAINT categories_path_unique UNIQUE (path),
    CONSTRAINT categories_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT categories_slug_format CHECK (slug ~ '^[a-z][a-z0-9-]{0,62}$'),
    CONSTRAINT categories_name_length CHECK (length(btrim(name)) BETWEEN 1 AND 160),
    CONSTRAINT categories_depth_nonnegative CHECK (depth >= 0),
    CONSTRAINT categories_depth_matches_path CHECK (depth = nlevel(path) - 1),
    CONSTRAINT categories_status_check CHECK (status IN ('active', 'inactive'))
);

CREATE INDEX categories_parent_index ON catalog.categories (parent_id);
CREATE INDEX categories_path_gist_index ON catalog.categories USING gist (path);
CREATE INDEX categories_active_slug_index ON catalog.categories (slug) WHERE status = 'active';
CREATE INDEX categories_security_domain_index ON catalog.categories (id) WHERE is_security_domain AND status = 'active';

CREATE TABLE catalog.part_catalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id integer NOT NULL,
    tenant_id integer NOT NULL,
    part_number text NOT NULL,
    part_name text NOT NULL,
    description text NOT NULL,
    commodity text NOT NULL,
    sub_commodity text NOT NULL,
    manufacturer text NOT NULL,
    vehicle_program text NOT NULL,
    region text NOT NULL,
    country text NOT NULL,
    plant text NOT NULL,
    model_year integer NOT NULL,
    material text NOT NULL,
    lifecycle_status text NOT NULL,
    supplier_status text NOT NULL,
    cost_usd numeric(12, 2) NOT NULL,
    weight_kg numeric(10, 3) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    security_domain_id bigint NOT NULL REFERENCES catalog.categories (id),
    primary_category_id bigint NOT NULL REFERENCES catalog.categories (id),
    visibility_status text NOT NULL DEFAULT 'organization',
    source_system text NOT NULL,
    source_record_id text,
    document_version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT part_catalog_part_number_unique UNIQUE (part_number),
    CONSTRAINT part_catalog_part_number_length CHECK (length(btrim(part_number)) BETWEEN 1 AND 160),
    CONSTRAINT part_catalog_part_name_length CHECK (length(btrim(part_name)) BETWEEN 1 AND 300),
    CONSTRAINT part_catalog_description_length CHECK (length(description) <= 20000),
    CONSTRAINT part_catalog_model_year_range CHECK (model_year BETWEEN 1886 AND 2100),
    CONSTRAINT part_catalog_cost_nonnegative CHECK (cost_usd >= 0),
    CONSTRAINT part_catalog_weight_nonnegative CHECK (weight_kg >= 0),
    CONSTRAINT part_catalog_visibility_check CHECK (visibility_status IN ('organization', 'restricted', 'internal')),
    CONSTRAINT part_catalog_source_system_length CHECK (length(btrim(source_system)) BETWEEN 1 AND 100),
    CONSTRAINT part_catalog_source_record_length CHECK (source_record_id IS NULL OR length(source_record_id) BETWEEN 1 AND 300),
    CONSTRAINT part_catalog_document_version_positive CHECK (document_version > 0)
);

CREATE UNIQUE INDEX part_catalog_source_record_unique
    ON catalog.part_catalog (source_system, source_record_id)
    WHERE source_record_id IS NOT NULL;

CREATE INDEX part_catalog_security_domain_index ON catalog.part_catalog (security_domain_id, active);
CREATE INDEX part_catalog_primary_category_index ON catalog.part_catalog (primary_category_id, active);
CREATE INDEX part_catalog_company_index ON catalog.part_catalog (company_id, active);
CREATE INDEX part_catalog_region_index ON catalog.part_catalog (region, active);
CREATE INDEX part_catalog_lifecycle_index ON catalog.part_catalog (lifecycle_status, active);
CREATE INDEX part_catalog_updated_index ON catalog.part_catalog (updated_at DESC, id);

CREATE TABLE catalog.part_categories (
    part_id bigint NOT NULL REFERENCES catalog.part_catalog (id) ON DELETE CASCADE,
    category_id bigint NOT NULL REFERENCES catalog.categories (id),
    assignment_type text NOT NULL,
    source text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (part_id, category_id),
    CONSTRAINT part_categories_assignment_type_check CHECK (assignment_type IN ('primary', 'secondary')),
    CONSTRAINT part_categories_source_check CHECK (source IN ('generated', 'manual', 'imported'))
);

CREATE UNIQUE INDEX part_categories_one_primary
    ON catalog.part_categories (part_id)
    WHERE assignment_type = 'primary';

CREATE INDEX part_categories_category_index ON catalog.part_categories (category_id, part_id);

CREATE FUNCTION catalog.validate_part_category_hierarchy()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, catalog, public
AS $function$
DECLARE
    domain_path ltree;
    primary_path ltree;
    domain_is_security boolean;
    domain_status text;
    primary_status text;
BEGIN
    SELECT path, is_security_domain, status
      INTO domain_path, domain_is_security, domain_status
      FROM catalog.categories
     WHERE id = NEW.security_domain_id;

    IF NOT FOUND OR NOT domain_is_security OR domain_status <> 'active' THEN
        RAISE EXCEPTION 'security_domain_id % must reference an active security domain', NEW.security_domain_id
            USING ERRCODE = '23514';
    END IF;

    SELECT path, status
      INTO primary_path, primary_status
      FROM catalog.categories
     WHERE id = NEW.primary_category_id;

    IF NOT FOUND OR primary_status <> 'active' OR NOT (primary_path <@ domain_path) THEN
        RAISE EXCEPTION 'primary_category_id % must be active and descend from security_domain_id %',
            NEW.primary_category_id, NEW.security_domain_id
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END
$function$;

CREATE TRIGGER part_catalog_validate_category_hierarchy
    BEFORE INSERT OR UPDATE OF security_domain_id, primary_category_id
    ON catalog.part_catalog
    FOR EACH ROW
    EXECUTE FUNCTION catalog.validate_part_category_hierarchy();

CREATE FUNCTION catalog.check_primary_assignment(checked_part_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, catalog
AS $function$
DECLARE
    expected_category_id bigint;
    actual_category_id bigint;
    primary_count bigint;
BEGIN
    SELECT primary_category_id
      INTO expected_category_id
      FROM catalog.part_catalog
     WHERE id = checked_part_id;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT count(*), max(category_id)
      INTO primary_count, actual_category_id
      FROM catalog.part_categories
     WHERE part_id = checked_part_id
       AND assignment_type = 'primary';

    IF primary_count <> 1 OR actual_category_id <> expected_category_id THEN
        RAISE EXCEPTION 'part % must have exactly one primary assignment matching category %',
            checked_part_id, expected_category_id
            USING ERRCODE = '23514';
    END IF;
END
$function$;

CREATE FUNCTION catalog.validate_part_catalog_primary_assignment()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, catalog
AS $function$
BEGIN
    PERFORM catalog.check_primary_assignment(NEW.id);
    RETURN NEW;
END
$function$;

CREATE FUNCTION catalog.validate_part_categories_primary_assignment()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, catalog
AS $function$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM catalog.check_primary_assignment(OLD.part_id);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') AND (TG_OP = 'INSERT' OR NEW.part_id IS DISTINCT FROM OLD.part_id) THEN
        PERFORM catalog.check_primary_assignment(NEW.part_id);
    END IF;

    RETURN COALESCE(NEW, OLD);
END
$function$;

CREATE CONSTRAINT TRIGGER part_catalog_primary_assignment_required
    AFTER INSERT OR UPDATE
    ON catalog.part_catalog
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION catalog.validate_part_catalog_primary_assignment();

CREATE CONSTRAINT TRIGGER part_categories_primary_assignment_matches
    AFTER INSERT OR UPDATE OR DELETE
    ON catalog.part_categories
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION catalog.validate_part_categories_primary_assignment();
